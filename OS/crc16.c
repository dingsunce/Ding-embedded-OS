#include "crc16.h"
//-----------------------------------------------------------------------------------------------------------
u16 Crc16_Add(u16 crcInit, u8 data)
{
  // polynomial ^ 16 + ^ 12 + ^ 5 + 1
  u16 crc = crcInit;
  crc ^= data;
  crc = (crc >> 8) | (crc << 8);
  crc ^= (crc & 0xff00) << 4;
  crc ^= (crc >> 8) >> 4;
  crc ^= (crc & 0xff00) >> 5;
  return crc;
}
//-----------------------------------------------------------------------------------------------------------
u16 Crc16_Calculate(const u8 *data, u16 len, u16 crcInit)
{
  u16 i;
  u16 crc = crcInit;

  for (i = 0; i < len; ++i)
  {
    crc = Crc16_Add(crc, *data);
    ++data;
  }

  return crc;
}
